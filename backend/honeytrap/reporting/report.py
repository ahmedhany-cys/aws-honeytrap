"""Incident investigation reports (Markdown and JSON) for a single attacker IP."""

from __future__ import annotations

import ipaddress
import json
from collections import Counter
from datetime import datetime, timezone
from typing import Any

from honeytrap.detection.commands import extract_urls
from honeytrap.detection.engine import build_profiles
from honeytrap.enrichment.service import summarise
from honeytrap.mitre.catalog import attack_version
from honeytrap.models import Alert, Event, Severity

ORIGIN_BANNER = {
    "live": "LIVE - captured from unsolicited internet traffic against an exposed sensor.",
    "simulation": "SIMULATION - generated by HoneyTrap's own controlled attack scripts. Not real attacker activity.",
    "synthetic": "SYNTHETIC - generated demo data. No honeypot or real attacker was involved.",
}

RECOMMENDATIONS = {
    "brute-force": "Block or rate-limit the source at the edge; confirm no production host accepts password auth.",
    "credential-stuffing": "Check the masked credential pairs against production accounts and enforce MFA/key auth.",
    "successful-login": "Review the full session transcript (ttylog) for follow-on activity.",
    "download": "Pull the URLs/hashes into the blocklist and search proxy/DNS logs for the same indicators.",
    "malware-retrieval": "Treat the payload hashes and URLs as IOCs; hunt for them across production telemetry.",
    "persistence": "Search production hosts for the same authorized_keys / cron / account changes.",
    "defense-evasion": "Verify history/audit logging is centralised and tamper-resistant on production hosts.",
    "reconnaissance": "Low priority on its own; correlate with authentication and download activity.",
    "scanning": "Add the source to edge deny lists if volume is high; no action needed for one-off scans.",
    "resource-hijacking": "Block the mining pool domains/IPs at egress across the estate.",
    "tunneling": "Confirm production SSH servers disable TCP forwarding (AllowTcpForwarding no).",
    "credential-access": "Ensure no real secrets exist in files reachable by SSH users on production hosts.",
    "repeated-sessions": "Persistent interest from this source; consider a longer-term block.",
    "suspicious-shell": "Extract decoded payloads from the ttylog for analysis in a sandbox.",
}


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _enrichment(ip: str, enrichment: dict | None) -> dict[str, Any]:
    record = (enrichment or {}).get(ip)
    if record:
        return summarise(record)
    try:
        private = not ipaddress.ip_address(ip).is_global
    except ValueError:
        private = False  # a pseudonymised address only ever stands for a public one
    # Only IPs whose alerts reach the enrichment threshold are looked up.
    return {"enrichment_status": "skipped_non_public" if private else "not_looked_up"}


def build_report(ip: str, events: list[Event], alerts: list[Alert],
                 enrichment: dict[str, dict[str, Any]] | None = None) -> dict[str, Any]:
    events = sorted((e for e in events if e.src_ip == ip), key=lambda e: e.timestamp)
    alerts = sorted((a for a in alerts if a.src_ip == ip or ip in a.related_ips),
                    key=lambda a: (-a.severity_level, a.first_seen))
    if not events:
        raise ValueError(f"no events for {ip}")
    profile = build_profiles(events, alerts, enrichment)[0]
    origins = sorted({e.data_origin for e in events})
    techniques: dict[str, dict[str, Any]] = {}
    for a in alerts:
        for t in a.techniques:
            entry = techniques.setdefault(t.technique_id, {"technique_id": t.technique_id, "name": t.name,
                                                           "tactics": t.tactics, "url": t.url,
                                                           "confidence": t.confidence, "evidence": [],
                                                           "rules": []})
            entry["evidence"] = list(dict.fromkeys(entry["evidence"] + t.evidence))[:8]
            entry["rules"] = sorted(set(entry["rules"]) | {a.rule_id})
    iocs = {
        "source_ip": ip,
        "urls": sorted({e.url for e in events if e.url and not e.url.startswith("upload:")}
                       | {u for e in events if e.command for u in extract_urls(e.command)}),
        "sha256": sorted({e.file_sha256 for e in events if e.file_sha256}),
        "client_versions": sorted({e.client_version for e in events if e.client_version}),
        "hassh": sorted({e.hassh for e in events if e.hassh}),
    }
    return {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "subject_ip": ip,
        "data_origins": origins,
        "attack_version": attack_version(),
        "profile": profile,
        "enrichment": _enrichment(ip, enrichment),
        "alerts": [a.to_dict() for a in alerts],
        "techniques": sorted(techniques.values(), key=lambda t: t["technique_id"]),
        "usernames": Counter(e.username for e in events if e.username).most_common(15),
        "passwords_masked": Counter(e.password_masked for e in events if e.password_masked).most_common(15),
        "commands": [{"timestamp": e.timestamp, "session_id": e.session_id, "command": e.command}
                     for e in events if e.event_type == "cowrie.command.input"],
        "timeline": [{"timestamp": e.timestamp, "event_type": e.event_type, "session_id": e.session_id,
                      "detail": e.command or e.url or (f"{e.username}/{e.password_masked}" if e.username else "")
                      or e.message or ""} for e in events][:500],
        "iocs": iocs,
        "recommendations": [RECOMMENDATIONS[c] for c in dict.fromkeys(a.classification for a in alerts)
                            if c in RECOMMENDATIONS],
    }


def render_markdown(report: dict[str, Any]) -> str:
    p = report["profile"]
    enr = report["enrichment"]
    lines = [
        f"# Incident investigation report - {report['subject_ip']}",
        "",
        f"> **Data origin:** {' / '.join(ORIGIN_BANNER[o] for o in report['data_origins'])}",
        "",
        f"Generated {report['generated_at']} by AWS HoneyTrap. MITRE ATT&CK Enterprise v{report['attack_version']}.",
        "Passwords are shown masked; full values exist only in the restricted raw log.",
        "",
        "## Summary",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Risk | **{p['risk_level']}** ({p['risk_score']}/100) |",
        f"| Actor type | {p['actor_type']} |",
        f"| First / last seen | {p['first_seen']} / {p['last_seen']} |",
        f"| Sessions | {p['sessions']} |",
        f"| Login attempts (failed / successful) | {p['login_attempts']} ({p['failed_logins']} / {p['successful_logins']}) |",
        f"| Commands executed | {p['commands']} |",
        f"| File transfer events | {p['downloads']} |",
        f"| Alerts | {p['alerts']} (max severity {p['max_severity']}) |",
        "",
        "## Threat intelligence enrichment",
        "",
    ]
    status = enr.get("enrichment_status")
    if status in (None, "none", "not_configured", "skipped_non_public", "unavailable", "deferred", "not_looked_up"):
        lines.append(f"No enrichment available (status: `{status}`). No reputation data is assumed.")
    else:
        if enr.get("synthetic_enrichment"):
            lines.append("> Enrichment below is **synthetic demo data**, not a real lookup.")
            lines.append("")
        for label, key in [("AbuseIPDB confidence", "abuse_confidence_score"), ("AbuseIPDB reports", "abuse_total_reports"),
                           ("VirusTotal malicious engines", "vt_malicious"), ("Country", "country_code"),
                           ("ISP / AS", "isp")]:
            if enr.get(key) is not None:
                lines.append(f"- {label}: {enr[key]}")
    lines += ["", "## Alerts", "", "| Severity | Rule | Summary | First seen |", "|---|---|---|---|"]
    for a in report["alerts"]:
        lines.append(f"| {a['severity']} | {a['rule_id']} {_md_escape(a['rule_name'])} | {_md_escape(a['summary'])} | {a['first_seen']} |")
    lines += ["", "## MITRE ATT&CK mapping", "",
              "| Technique | Tactic(s) | Confidence | Evidence |", "|---|---|---|---|"]
    for t in report["techniques"]:
        lines.append(f"| [{t['technique_id']} {t['name']}]({t['url']}) | {', '.join(t['tactics'])} | "
                     f"{t['confidence']} | {_md_escape('; '.join(t['evidence'][:3]))} |")
    if not report["techniques"]:
        lines.append("| - | - | - | No technique supported by the evidence |")
    lines += ["", "## Credentials attempted (masked)", ""]
    lines.append("Usernames: " + (", ".join(f"`{u}` ({c})" for u, c in report["usernames"]) or "none"))
    lines.append("")
    lines.append("Passwords: " + (", ".join(f"`{pw}` ({c})" for pw, c in report["passwords_masked"]) or "none"))
    lines += ["", "## Commands", ""]
    if report["commands"]:
        lines.append("```text")
        lines += [f"{c['timestamp']}  {c['command']}" for c in report["commands"][:100]]
        lines.append("```")
    else:
        lines.append("No commands executed.")
    lines += ["", "## Indicators of compromise", ""]
    for key, values in report["iocs"].items():
        if values:
            lines.append(f"- **{key}**: " + ", ".join(f"`{v}`" for v in (values if isinstance(values, list) else [values])))
    lines += ["", "## Recommended actions", ""]
    lines += [f"- {r}" for r in report["recommendations"]] or ["- No action required."]
    lines += ["", "## Timeline (first 100 events)", "", "| Time | Event | Session | Detail |", "|---|---|---|---|"]
    for t in report["timeline"][:100]:
        lines.append(f"| {t['timestamp']} | {t['event_type']} | {t['session_id'] or ''} | {_md_escape(t['detail'])[:120]} |")
    return "\n".join(lines) + "\n"


def render_json(report: dict[str, Any]) -> str:
    return json.dumps(report, indent=2, default=str)


def max_severity(report: dict[str, Any]) -> Severity:
    return max((Severity.parse(a["severity"]) for a in report["alerts"]), default=Severity.INFORMATIONAL)
